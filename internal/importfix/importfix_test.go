package importfix_test

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/malivvan/binco/internal/importfix"
)

func process(t *testing.T, src string) string {
	t.Helper()
	out, err := importfix.Process([]byte(src))
	if err != nil {
		t.Fatalf("Process: %v", err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "", out, parser.AllErrors); err != nil {
		t.Fatalf("Process returned source that does not parse: %v\n%s", err, out)
	}
	return string(out)
}

// TestPrunesUnusedImports covers the reason the generator needs this step: it
// emits a superset of imports and Go rejects the unused ones.
func TestPrunesUnusedImports(t *testing.T) {
	src := `package p

import (
	"fmt"
	"strings"

	"github.com/malivvan/binco/varnum"
	"github.com/malivvan/binco/scalar"
)

func f(v int, bs []byte) int { return varnum.Int.Marshal(v, bs) }
`
	got := process(t, src)
	if !strings.Contains(got, `"github.com/malivvan/binco/varnum"`) {
		t.Fatalf("the used import was removed:\n%s", got)
	}
	for _, unused := range []string{`"fmt"`, `"strings"`, `"github.com/malivvan/binco/scalar"`} {
		if strings.Contains(got, unused) {
			t.Fatalf("the unused import %s was kept:\n%s", unused, got)
		}
	}
}

// TestRemovesTheWholeBlock checks that a file with no used imports does not keep
// an empty import declaration behind.
func TestRemovesTheWholeBlock(t *testing.T) {
	src := `package p

import (
	"fmt"
)

func f() {}
`
	got := process(t, src)
	if strings.Contains(got, "import") {
		t.Fatalf("an empty import block was kept:\n%s", got)
	}
	if !strings.Contains(got, "package p") || !strings.Contains(got, "func f()") {
		t.Fatalf("content was lost:\n%s", got)
	}
}

// TestKeepsAliasedBlankAndDotImports checks the imports whose qualifier is not a
// selector: an alias, a blank import and a dot import.
func TestKeepsAliasedBlankAndDotImports(t *testing.T) {
	src := `package p

import (
	_ "embed"
	. "strings"
	sc "github.com/malivvan/binco/scalar"
	"github.com/malivvan/binco/varnum"
)

func f(bs []byte) int {
	_ = Contains
	return sc.Int.Size(0) + varnum.Int.Size(0)
}
`
	got := process(t, src)
	for _, want := range []string{`_ "embed"`, `. "strings"`, `sc "github.com/malivvan/binco/scalar"`, `"github.com/malivvan/binco/varnum"`} {
		if !strings.Contains(got, want) {
			t.Fatalf("import %s was removed:\n%s", want, got)
		}
	}
}

// TestDeduplicatesByPath covers a caller that passes an aliased import while the
// type-driven pass adds the same path without an alias.
func TestDeduplicatesByPath(t *testing.T) {
	src := `package p

import (
	"github.com/example/serializers"
	ser "github.com/example/serializers"
)

func f() { _ = ser.Foo }
`
	got := process(t, src)
	if strings.Count(got, "github.com/example/serializers") != 1 {
		t.Fatalf("the duplicate import was kept:\n%s", got)
	}
	if !strings.Contains(got, `ser "github.com/example/serializers"`) {
		t.Fatalf("the aliased import was not the one kept:\n%s", got)
	}
}

// TestGroupsStandardLibraryFirst checks the layout goimports used to produce.
func TestGroupsStandardLibraryFirst(t *testing.T) {
	src := `package p

import (
	"github.com/malivvan/binco/varnum"
	"time"
	"fmt"
)

func f(bs []byte) int {
	_ = time.Now
	_ = fmt.Sprint
	return varnum.Int.Size(0)
}
`
	got := process(t, src)
	fmtIndex := strings.Index(got, `"fmt"`)
	timeIndex := strings.Index(got, `"time"`)
	bincoIndex := strings.Index(got, `"github.com/malivvan/binco/varnum"`)
	if fmtIndex < 0 || timeIndex < 0 || bincoIndex < 0 {
		t.Fatalf("an import is missing:\n%s", got)
	}
	if fmtIndex >= bincoIndex || timeIndex >= bincoIndex {
		t.Fatalf("the standard library is not grouped first:\n%s", got)
	}
	if !strings.Contains(got, "\"time\"\n\n\t\"github.com") {
		t.Fatalf("the groups are not separated by a blank line:\n%s", got)
	}
}

// TestAddsNothingUnknown checks that a qualifier without an import is left for
// the compiler: guessing a path would be worse than a clear error.
func TestAddsNothingUnknown(t *testing.T) {
	src := `package p

func f() { _ = unknown.Thing() }
`
	got := process(t, src)
	if strings.Contains(got, "import") {
		t.Fatalf("an import was invented:\n%s", got)
	}
}

// TestReportsParseErrors checks that invalid source is reported instead of being
// formatted into something else.
func TestReportsParseErrors(t *testing.T) {
	if _, err := importfix.Process([]byte("package p\n\nfunc {")); err == nil {
		t.Fatal("Process accepted invalid source")
	}
}

// TestPreservesComments checks that the comments around the import block survive
// the rewrite.
func TestPreservesComments(t *testing.T) {
	src := `// Code generated by binco/codegen. DO NOT EDIT.

package p

// The import block follows.
import (
	"fmt"
)

// f is kept.
func f() {}
`
	got := process(t, src)
	for _, want := range []string{"Code generated", "The import block follows.", "f is kept."} {
		if !strings.Contains(got, want) {
			t.Fatalf("comment %q was lost:\n%s", want, got)
		}
	}
}

// TestPrefersTheAliasWhenBothImportsAreUsed covers the deduplication branch where
// the plain import comes first but only the aliased one can be referenced.
func TestPrefersTheAliasWhenBothImportsAreUsed(t *testing.T) {
	src := `package p

import (
	"github.com/example/serializers"
	ser "github.com/example/serializers"
)

var _ = serializers.Foo
var _ = ser.Bar
`
	got := process(t, src)
	if strings.Count(got, "github.com/example/serializers") != 1 {
		t.Fatalf("the duplicate import was kept:\n%s", got)
	}
	if !strings.Contains(got, `ser "github.com/example/serializers"`) {
		t.Fatalf("the aliased import was not the one kept:\n%s", got)
	}
}

// TestFileWithoutImports checks that source with no import declaration is
// returned formatted and unchanged.
func TestFileWithoutImports(t *testing.T) {
	src := "package p\n\nfunc  f( )  {}\n"
	got := process(t, src)
	want := "package p\n\nfunc f() {}\n"
	if got != want {
		t.Fatalf("Process = %q, want %q", got, want)
	}
}
