func TestGeneratedCodeCompilesAndRuns(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compilation test in short mode")
	}
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("the go tool is not available")
	}
	repoRoot, err := filepath.Abs("..")
	if err != nil {
		t.Fatalf("Abs: %v", err)
	}

	dir := t.TempDir()
	modelDir := filepath.Join(dir, "testdata")
	if err = os.MkdirAll(modelDir, 0o755); err != nil {
		t.Fatalf("MkdirAll: %v", err)
	}

	fixture, err := os.ReadFile(filepath.Join(repoRoot, "testdata", "model.go"))
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	if err = os.WriteFile(filepath.Join(modelDir, "model.go"), fixture, 0o644); err != nil {
		t.Fatalf("WriteFile: %v", err)
	}

	g := newGenerator(t,
		genopts.WithPackage("testdata"),
	)
	for _, add := range []func() error{
		func() error {
			return g.AddStruct(reflect.TypeFor[testdata.SimpleStruct]())
		},
		func() error {
			return g.AddStruct(reflect.TypeFor[testdata.IgnoredFieldStruct](),
				stopts.WithField(), stopts.WithField(field.WithIgnore()))
		},
		func() error {
			return g.AddStruct(reflect.TypeFor[testdata.Time](),
				stopts.WithUnderlyingTime())
		},
		func() error {
			return g.AddStruct(reflect.TypeFor[testdata.FullStruct]())
		},
		func() error {
			return g.AddDefinedType(reflect.TypeFor[testdata.Int](),
				tpopts.WithValidator("ValidateInt"))
		},
		func() error {
			return g.AddDefinedType(reflect.TypeFor[testdata.IntSlice]())
		},
		func() error {
			return g.RegisterInterface(reflect.TypeFor[testdata.Universal](),
				intropts.WithStructImpl(reflect.TypeFor[testdata.StructImpl]()),
				intropts.WithDefinedTypeImpl(reflect.TypeFor[testdata.DefinedImpl]()))
		},
		func() error {
			return g.RegisterVersioned(reflect.TypeFor[testdata.VerFoo](),
				veropts.WithVersion(reflect.TypeFor[testdata.VerFooVer1](), "MigrateVerFooVer1"),
				veropts.WithCurrentVersion(reflect.TypeFor[testdata.VerFooVer2]()))
		},
	} {
		if err = add(); err != nil {
			t.Fatalf("generator: %v", err)
		}
	}
	src, err := g.Generate()
	if err != nil {
		t.Fatalf("Generate: %v\n%s", err, src)
	}
	if err = os.WriteFile(filepath.Join(modelDir, "model_binco.gen.go"), src, 0o644); err != nil {
		t.Fatalf("WriteFile: %v", err)
	}

	gomod := "module fixture\n\ngo " + moduleGoVersion(t, repoRoot) + "\n\n" +
		"require github.com/malivvan/binco v0.0.0\n\n" +
		"replace github.com/malivvan/binco => " + repoRoot + "\n"
	if err = os.WriteFile(filepath.Join(dir, "go.mod"), []byte(gomod), 0o644); err != nil {
		t.Fatalf("WriteFile: %v", err)
	}
	// The module has no third-party dependencies, so a go.sum only exists if
	// something added one; copy it when it is there.
	if goSum, readErr := os.ReadFile(filepath.Join(repoRoot, "go.sum")); readErr == nil {
		if err = os.WriteFile(filepath.Join(dir, "go.sum"), goSum, 0o644); err != nil {
			t.Fatalf("WriteFile: %v", err)
		}
	} else if !os.IsNotExist(readErr) {
		t.Fatalf("ReadFile: %v", readErr)
	}
	program := `package main

import (
	"bytes"
	"fmt"
	"os"
	"time"

	"fixture/testdata"

	"github.com/malivvan/binco"
)

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}

func main() {
	s := testdata.SimpleStruct{Num: 300, Str: "hi"}
	bs := binco.Encode(testdata.SimpleStructBinco, s)
	if fmt.Sprint(bs) != "[216 4 2 104 105]" {
		fail("unexpected encoding %v", bs)
	}
	got, err := binco.Decode(testdata.SimpleStructBinco, bs)
	if err != nil || got != s {
		fail("round trip: %+v %v", got, err)
	}
	n, err := testdata.SimpleStructBinco.Skip(bs)
	if err != nil || n != len(bs) {
		fail("skip: %d %v", n, err)
	}

	ig := testdata.IgnoredFieldStruct{Num: 1, Str: "ignored"}
	gotIg, err := binco.Decode(testdata.IgnoredFieldStructBinco, binco.Encode(testdata.IgnoredFieldStructBinco, ig))
	if err != nil || gotIg.Num != 1 || gotIg.Str != "" {
		fail("ignored field: %+v %v", gotIg, err)
	}

	now := time.Date(2024, 5, 6, 7, 8, 9, 0, time.UTC)
	tv := testdata.Time(now)
	gotT, err := binco.Decode(testdata.TimeBinco, binco.Encode(testdata.TimeBinco, tv))
	if err != nil || !time.Time(gotT).Equal(now) {
		fail("time: %v %v", time.Time(gotT), err)
	}

	var shape testdata.Universal = testdata.StructImpl{Value: 3}
	shapeBS := binco.Encode(testdata.UniversalBinco, shape)
	gotShape, err := binco.Decode(testdata.UniversalBinco, shapeBS)
	if err != nil || gotShape != shape {
		fail("interface: %+v %v", gotShape, err)
	}

	cur := testdata.VerFoo(testdata.VerFooVer2("current"))
	gotVer, err := binco.Decode(testdata.VerFooBinco, binco.Encode(testdata.VerFooBinco, cur))
	if err != nil || gotVer != cur {
		fail("versioned: %v %v", gotVer, err)
	}
	oldBS := binco.Encode(testdata.VerFooVer1TypedBinco, testdata.VerFooVer1(5))
	gotVer, err = binco.Decode(testdata.VerFooBinco, oldBS)
	if err != nil || gotVer != testdata.VerFoo(testdata.VerFooVer2("migrated")) {
		fail("migration: %v %v", gotVer, err)
	}

	full := testdata.FullStruct{
		B: true, By: 7, I: -1, I8: -2, I16: -3, I32: -4, I64: -5,
		U: 1, U8: 2, U16: 3, U32: 4, U64: 5,
		F32: 1.5, F64: -2.5, S: "str", Bs: []byte{1, 2},
		Sl: []int{1, 2}, M: map[string]int{"a": 1}, A: [3]int{1, 2, 3},
		P: new(int), T: now, IF: testdata.DefinedImpl("x"),
	}
	*full.P = 42
	fbs := binco.Encode(testdata.FullStructBinco, full)
	gotFull, err := binco.Decode(testdata.FullStructBinco, fbs)
	if err != nil {
		fail("full struct: %v", err)
	}
	if gotFull.S != full.S || gotFull.I64 != full.I64 || *gotFull.P != 42 || gotFull.IF.Describe() != "x" {
		fail("full struct mismatch: %+v", gotFull)
	}
	if !bytes.Equal(fbs, binco.Encode(testdata.FullStructBinco, gotFull)) {
		fail("full struct is not re-encodable")
	}

	// IntSlice uses the default slice serializer.
	is := testdata.IntSlice{1, 2, 3}
	gotIS, err := binco.Decode(testdata.IntSliceBinco, binco.Encode(testdata.IntSliceBinco, is))
	if err != nil || len(gotIS) != 3 || gotIS[2] != 3 {
		fail("int slice: %v %v", gotIS, err)
	}

	fmt.Println("OK")
}
`
	if err = os.WriteFile(filepath.Join(dir, "main.go"), []byte(program), 0o644); err != nil {
		t.Fatalf("WriteFile: %v", err)
	}

	cmd := exec.Command("go", "run", ".")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOFLAGS=-mod=mod")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("go run failed: %v\n%s", err, out)
	}
	if !strings.Contains(string(out), "OK") {
		t.Fatalf("unexpected program output: %s", out)
	}
}

func moduleGoVersion(t *testing.T, dir string) string {
	t.Helper()
	bs, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		t.Fatalf("ReadFile: %v", err)
	}
	for line := range strings.SplitSeq(string(bs), "\n") {
		line = strings.TrimSpace(line)
		if rest, ok := strings.CutPrefix(line, "go "); ok {
			return strings.TrimSpace(rest)
		}
	}
	t.Fatal("no go directive in go.mod")
	return ""
}

